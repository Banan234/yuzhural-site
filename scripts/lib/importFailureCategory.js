export function classifyImportFailure(report) {
  const message = `${report.diagnostic || ''} ${report.errorCode || ''} ${report.message || ''}`;
  const rule = rules.find(([, pattern]) => pattern.test(message));
  const [code, , title, action] = rule || [
    'unknown',
    null,
    'Неизвестная ошибка импорта',
    'Проверить подробный отчёт и исходное сообщение; причина ещё не определена.',
  ];
  return { code, title, action };
}
