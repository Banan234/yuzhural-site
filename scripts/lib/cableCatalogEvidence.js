export function collectCableCardEvidence(detail) {
  const found = new Map();
  const add = (statement, source) => {
    const phrase = typeof statement === 'string' && statement.trim().replace(/[.!]$/u,'');
    for (const [label,value] of Object.entries(facts.get(phrase) ?? {})) {
      if (!found.has(label)) found.set(label,[]);
      found.get(label).push({ value, source, statement });
    }
  };
  const decoded = detail.designationDecoded;
  if (!decoded?.warnings?.length && !decoded?.unknown?.length) {
    for (const [index,token] of (decoded?.tokens ?? []).entries())
      add(token.text, 'designationDecoded.tokens['+index+']');
  }
  const construction = detail.catalogContent?.construction;
  if (typeof construction === 'string')
    for (const statement of construction.split(/(?<=\.)\s+(?=[А-ЯЁ])/u)) add(statement, 'catalogContent.construction');
  return found;
}
