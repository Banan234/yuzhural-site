export function getCableComparisons(value) {
  const decoded = decodeCableDesignation(value);
  if (
    !decoded.family ||
    decoded.unknown ||
    decoded.specification?.warnings.length
  )
    return [];
  return CABLE_COMPARISONS.filter((group) =>
    group.marks.includes(decoded.family.mark)
  );
}
