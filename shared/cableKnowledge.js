export function normalizeKnowledgeMark(value) {
  return String(value || '')
    .trim()
    .toUpperCase()
    .replace(/\s+/g, '')
    .replace(/Ё/g, 'Е');
}

// Сопоставляем только известное семейство и понятные индексы, без универсальной расшифровки букв.
export function decodeCableDesignation(value) {
  const input = String(value || '')
    .trim()
    .slice(0, 250);
  const specification = findCableSpecification(input);
  const markPart = specification
    ? input.slice(0, specification.index).trim()
    : input;
  const tail = specification
    ? input.slice(specification.index + specification.length).trim()
    : '';
  const normalized = normalizeKnowledgeMark(markPart).replace(
    /^КАБЕЛЬ|^ПРОВОД/u,
    ''
  );
  const family = [...CABLE_KNOWLEDGE]
    .sort((a, b) => b.mark.length - a.mark.length)
    .find((item) => normalized.startsWith(normalizeKnowledgeMark(item.mark)));
  if (!family)
    return {
      input,
      family: null,
      specification,
      tokens: [],
      unknown: markPart,
    };
  let remainder = normalized.slice(normalizeKnowledgeMark(family.mark).length);
  // Индексы встречаются и после размера в исходном прайсе. Не теряем их при разборе.
  const voltageMatch = tail.match(/^[-–]?\s*(\d+(?:[.,]\d+)?)\s*кВ$/iu);
  const voltageKv = voltageMatch
    ? Number(voltageMatch[1].replace(',', '.'))
    : null;
  if (tail && !voltageMatch) remainder += normalizeKnowledgeMark(tail);
  const tokens = family.tokens.map(([code, text]) => ({ code, text }));
  const suffixes = [
    [
      /^-?НГ\(([АБВГД]|A|B|C|D)\)/u,
      (match) =>
        `Не распространяет горение при групповой прокладке; категория ${match[1]}`,
    ],
    [
      /^-?НГ/u,
      () =>
        'Индекс нераспространения горения; категория в обозначении не указана',
    ],
    [
      /^-?FRLS/u,
      () => 'Огнестойкое исполнение с пониженным дымо- и газовыделением',
    ],
    [
      /^-?FRHF/u,
      () => 'Огнестойкое исполнение с полимерными композициями без галогенов',
    ],
    [
      /^-?LSLTX/u,
      () =>
        'Пониженное дымо- и газовыделение, низкая токсичность продуктов горения',
    ],
    [/^-?LS/u, () => 'Пониженное дымо- и газовыделение'],
    [/^-?HF/u, () => 'Полимерные композиции без галогенов'],
    [
      /^-?ХЛ/u,
      () => 'Холодостойкое исполнение; температурный диапазон уточняют по ТУ',
    ],
    [
      family.mark === 'ВВГ' || family.mark === 'АВВГ' ? /^-?П/u : /$^/u,
      () => 'Плоское исполнение силового кабеля',
    ],
    [/^-?ГОСТ/u, () => 'Указано изготовление по ГОСТ; нужен номер стандарта'],
  ];
  let fire = '';
  for (let i = 0; i < 10 && remainder; i += 1) {
    const found = suffixes.find(([pattern]) => pattern.test(remainder));
    if (!found) break;
    const match = remainder.match(found[0]);
    const code = match[0].replace(/^-/, '');
    if (/НГ|LS|HF|FR/.test(code)) fire += code;
    tokens.push({ code, text: found[1](match) });
    remainder = remainder.slice(match[0].length);
  }
  if (remainder === '-') remainder = '';
  let size = '';
  if (specification && !specification.warnings.length) {
    const { cores, groupCores, crossSection, groundCores, groundSection } =
      specification;
    if (family.mark === 'ТППэп' && groupCores === 2)
      size = `${cores} пар по 2 жилы, диаметр жилы ${crossSection} мм`;
    else if (!groupCores && cores && crossSection)
      size = `${cores} жил × ${crossSection} мм²${groundCores ? ` + ${groundCores} жил × ${groundSection} мм²` : ''}`;
    else
      size = `Конструкция: ${input.slice(specification.index, specification.index + specification.length)}. Размеры групп уточняйте по документации.`;
  }
  return {
    input,
    family,
    specification,
    tokens,
    size,
    fire,
    voltageKv,
    unknown: remainder,
    mark: markPart,
  };
}

