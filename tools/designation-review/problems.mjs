export function reviewProblems(product, name) {
  const { unknown, warnings } = product.designationDecoded;
  const compareSintenax =
    product.sku === 'YU-0002839' &&
    /^КВВГ\s+10\s*[хx×]\s*1\s+FRLS\s+SINTENAX\s+PIRELLI$/iu.test(name.trim());
  return [
    ...unknown.map((code) => {
      const index = code.trim().toLocaleUpperCase('ru');
      const lookupIndex =
        index === '1' && unknown.includes('мкл') ? 'МКЛ' : index;
      const [type, title, , check] = indexRules.find((rule) =>
        rule[2].test(lookupIndex)
      ) || [
        'index',
        'Прочие индексы и обозначения',
        null,
        'Найдите это обозначение в документации конкретного изготовителя или сверьте с биркой. Зафиксируйте, является ли оно частью марки, артикулом или пометкой прайса.',
      ];
      const kuptexScreen = index === 'Э' && /^КУПТекс\s+ПЭл\s+э/iu.test(name);
      return {
        id: 'index:' + index,
        type,
        title,
        label: 'Обозначение «' + index + '»',
        check: kuptexScreen
          ? 'В схеме «Энергостроя» общий экран «Эл» — лужёная медная оплётка, а «ЭЭл» — комбинированный общий экран. В прайсе записано «ПЭл энг(А)HF». Сверьте по бирке или паспорту, указан ли «ПЭл», «ПЭЭл» или иное исполнение.'
          : check,
        ...(kuptexScreen
          ? {
              url: 'https://kuptex.ru/decoding/',
              source: 'Схема «Энергостроя», пункты 1 и 3',
            }
          : {}),
        ...(compareSintenax ? sintenaxComparison[index] : {}),
        ...smokeAndGasNotes[product.mark.toUpperCase()]?.[index],
      };
    }),
    ...warnings.map((warning) => {
      const [type, title, , check] = warningRules.find((rule) =>
        rule[2].test(warning)
      ) || [
        'warning',
        'Другое предупреждение',
        null,
        'Сверьте указанное расхождение с документацией на точное исполнение и запишите подтверждённое значение.',
      ];
      return {
        id: 'warning:' + warning,
        type,
        title,
        label: title,
        check,
        warning,
      };
    }),
  ];
}
